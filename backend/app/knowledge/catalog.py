def _build_concepts() -> tuple[KnowledgeConcept, ...]:
    return tuple(
        KnowledgeConcept(
            domain=domain,
            canonical=canonical,
            aliases=tuple(dict.fromkeys((canonical, *aliases))),
            weight=DOMAIN_WEIGHTS.get(domain, 5),
        )
        for domain, domain_concepts in DOMAIN_CONCEPTS.items()
        for canonical, aliases in domain_concepts.items()
    )


CONCEPTS = _build_concepts()
CONCEPT_BY_KEY = {
    (concept.domain, concept.canonical): concept
    for concept in CONCEPTS
}
ALIAS_TO_CONCEPT = {
    alias.lower(): concept
    for concept in CONCEPTS
    for alias in concept.aliases
}
SORTED_ALIASES = tuple(sorted(ALIAS_TO_CONCEPT, key=len, reverse=True))


def concept_variants(value: str) -> tuple[str, ...]:
    concept = ALIAS_TO_CONCEPT.get(value.lower())
    if not concept:
        return (value.lower(),)
    return tuple(alias.lower() for alias in concept.aliases)
